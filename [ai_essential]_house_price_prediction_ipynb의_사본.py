"""## 4. 심층신경망 모델을 구성하고 학습하여 TEST를 예측해보세요.
- TEST의 예측 결과는 `comp.prediction`에 대입해주세요. **torch.tensor** 형태여야합니다.
"""

# DataLoader 생성
from torch.utils.data import DataLoader, TensorDataset
train_loader = DataLoader(TensorDataset(X, y), batch_size=32, shuffle=True)

# DNN 모델 구성
class DNN(nn.Module):
    def __init__(self):
        super().__init__()
        # input features를 79로 변경
        self.fc1 = nn.Linear(79, 64)
        self.relu1 = nn.ReLU()
        self.fc2 = nn.Linear(64, 32)
        self.relu2 = nn.ReLU()
        self.fc3 = nn.Linear(32, 1)
    def forward(self, x):
        x = self.fc1(x)
        x = self.relu1(x)
        x = self.fc2(x)
        x = self.relu2(x)
        x = self.fc3(x)
        return x

model = DNN().to(device)
summary(model)

# 손실함수 및 옵티마이저 설정
criterion = nn.MSELoss()
optimizer = optim.Adam(model.parameters(), lr=0.001)

X.shape

# 모델 학습 과정 구현

epochs = 10
for epoch in range(epochs):

    running_loss = 0.0

    # 모델 학습 모드 설정
    model.train()

    for inputs, labels in train_loader:
        inputs = inputs.to(device)
        labels = labels.to(device)


        # 순전파 > outputs
        outputs = model(inputs)

        # 손실 계산 > loss
        loss = criterion(outputs, labels)

        # 누적된 기울기 초기화
        optimizer.zero_grad()

        # 역전파
        loss.backward()

        # 파라미터 업데이트
        optimizer.step()


        running_loss += loss.item()

    if epoch % 100 == 0:
        print(f'Epoch [{epoch+1}/{epochs}], Loss: {running_loss / len(train_loader)}')

# 학습된 모델의 TEST 예측

epochs = 10
for epoch in range(10): # epochs 변수의 값 만큼 반복
    running_loss = 0.0

    # 모델을 학습모드로 설정
    model.train()

    for inputs, labels in train_loader:
        inputs = inputs.to(device)
        labels = labels.to(device)

        # inputs에 대한 출력값(outputs) 계산
        outputs = model(inputs)

        # 출력값(outputs)과 정답값(labels)의 손실 계산
        loss = criterion(outputs, labels)

        # 기울기 초기화
        optimizer.zero_grad()

        # 손실(loss)에 대한 각 파라미터의 기울기(gradient)를 계산
        loss.backward()

        # 계산된 기울기를 사용하여 각 파라미터를 업데이트
        optimizer.step()

        running_loss += loss.item()

    print(f'Epoch {epoch+1}, Loss: {running_loss / len(train_loader)}') # 에폭별 손실 값 출력
# ================================================================== #

# TEST 데이터에 대한 예측 수행
model.eval()  # 모델을 평가 모드로 설정
with torch.no_grad():  # 기울기 계산 비활성화
    predictions = model(TEST.to(device))  # TEST 데이터에 대한 예측 수행

# comp.prediction에 TEST 예측 결과 대입
comp.prediction = predictions.squeeze() # prediction 크기 조정

